type ChatTab = "prompts" | "documents" | "insights" | "history"

const tabOptions: { id: ChatTab; label: string; description: string }[] = [
  {
    id: "prompts",
    label: "Prompts",
    description: "Jump back into a conversation with one tap.",
  },
  {
    id: "documents",
    label: "Documents",
    description: "Review drafts and deliverables from recent sessions.",
  },
  {
    id: "insights",
    label: "Insights",
    description: "Key takeaways and recommendations generated by AI.",
  },
  {
    id: "history",
    label: "History",
    description: "Search prior chats and continue the thread.",
  },
]

export function ChatResultsPanel({ files }: ChatResultsPanelProps) {
  const [activeTab, setActiveTab] = useState<ChatTab>("prompts")
  const [searchQuery, setSearchQuery] = useState("")

  const filteredHistory = mockChatHistory.filter(
    (chat) =>
      chat.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
      chat.preview.toLowerCase().includes(searchQuery.toLowerCase()),
  )
  const activeTabMeta = tabOptions.find((tab) => tab.id === activeTab)

  const renderTabContent = () => {
    switch (activeTab) {
      case "prompts":
        return (
          <div className="space-y-2">
            {quickPrompts.map((prompt, index) => (
              <button
                key={index}
                type="button"
                className="w-full rounded-lg border border-border/40 bg-background/80 px-3 py-2 text-left text-sm text-foreground transition hover:border-border/60 hover:bg-background/90"
              >
                <div className="flex items-start gap-2">
                  <span className="mt-1 text-muted-foreground">
                    <MessageSquare className="h-4 w-4" />
                  </span>
                  <span className="leading-snug">{prompt}</span>
                </div>
              </button>
            ))}
          </div>
        )
      case "documents":
        return (
          <div className="space-y-2">
            {mockDocuments.map((doc) => (
              <div
                key={doc.id}
                className="rounded-lg border border-border/40 bg-background/80 px-3 py-2 text-sm text-foreground"
              >
                <div className="flex items-start justify-between gap-2">
                  <div className="flex flex-col gap-1">
                    <div className="flex items-center gap-2">
                      <FileText className="h-4 w-4 text-muted-foreground" />
                      <span className="font-medium leading-tight">{doc.title}</span>
                    </div>
                    <p className="text-xs text-muted-foreground">
                      {doc.type} • {doc.size}
                    </p>
                  </div>
                  <div className="flex items-center gap-2">
                    <Badge variant={doc.status === "Generated" ? "default" : "secondary"} className="text-[10px]">
                      {doc.status}
                    </Badge>
                    <Button variant="ghost" size="sm">
                      <Download className="h-3 w-3" />
                    </Button>
                  </div>
                </div>
              </div>
            ))}
          </div>
        )
      case "insights":
        return (
          <div className="space-y-2">
            {mockInsights.map((insight) => (
              <div
                key={insight.id}
                className="rounded-lg border border-border/40 bg-background/80 px-3 py-2 text-sm text-foreground"
              >
                <div className="flex items-start justify-between gap-2">
                  <h5 className="font-medium leading-tight">{insight.title}</h5>
                  <Badge variant="outline" className="text-[10px]">
                    {Math.round(insight.confidence * 100)}% confidence
                  </Badge>
                </div>
                <p className="mt-2 text-xs leading-relaxed text-muted-foreground">{insight.description}</p>
                <p className="mt-1 text-[11px] text-muted-foreground/80">{insight.sources} sources analyzed</p>
              </div>
            ))}
          </div>
        )
      case "history":
        return (
          <div className="space-y-3">
            <div className="relative">
              <Search className="absolute left-3 top-1/2 h-3 w-3 -translate-y-1/2 text-muted-foreground" />
              <Input
                placeholder="Search chat history..."
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                className="pl-9 text-sm"
              />
            </div>
            <div className="space-y-2">
              {filteredHistory.map((chat) => (
                <button
                  key={chat.id}
                  type="button"
                  className="w-full rounded-lg border border-border/40 bg-background/80 p-3 text-left transition hover:border-border/60 hover:bg-background/90"
                >
                  <div className="mb-1 flex items-center justify-between">
                    <div className="flex items-center gap-2">
                      <History className="h-3 w-3 text-muted-foreground" />
                      <span className="text-sm font-medium leading-tight text-foreground">{chat.title}</span>
                    </div>
                    <Badge variant="outline" className="text-[10px]">
                      {chat.messageCount} messages
                    </Badge>
                  </div>
                  <p className="text-xs text-muted-foreground">{chat.preview}</p>
                  <p className="mt-1 text-[11px] text-muted-foreground/70">
                    {new Date(chat.timestamp).toLocaleDateString()}
                  </p>
                </button>
              ))}
            </div>
          </div>
        )
    }
  }

  return (
    <div className="flex h-full flex-col gap-4">
      {files.length > 0 && (
        <div className="rounded-lg border border-border/40 bg-secondary/40 px-3 py-2">
          <p className="text-xs text-muted-foreground">
            Using context from {files.filter((f) => f.status === "completed").length} uploaded files
          </p>
        </div>
      )}

      <div className="space-y-3">
        <div className="space-y-1">
          <h4 className="text-sm font-semibold text-foreground">AI Assistant</h4>
          {activeTabMeta && <p className="text-xs text-muted-foreground">{activeTabMeta.description}</p>}
        </div>
        <div className="flex flex-col gap-2">
          {tabOptions.map((tab) => (
            <Button
              key={tab.id}
              type="button"
              size="sm"
              variant="outline"
              className={cn(
                getToggleButtonClasses(activeTab === tab.id),
                "w-full justify-start rounded-lg text-xs font-medium",
              )}
              onClick={() => setActiveTab(tab.id)}
            >
              {tab.label}
            </Button>
          ))}
        </div>
      </div>

      <div className="flex-1 overflow-y-auto pr-1">{renderTabContent()}</div>

      <div className="space-y-2 border-t border-border/30 pt-3">
        <h4 className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">Document Generation</h4>
        <div className="flex flex-col gap-2">
          <Button variant="outline" size="sm" className="w-full justify-start gap-2 bg-transparent">
            <MessageSquare className="h-3 w-3" />
            Draft Email
          </Button>
          <Button variant="outline" size="sm" className="w-full justify-start gap-2 bg-transparent">
            <FileText className="h-3 w-3" />
            Create Proposal
          </Button>
          <Button variant="outline" size="sm" className="w-full justify-start gap-2 bg-transparent">
            <Users className="h-3 w-3" />
            Schedule Meeting
          </Button>
          <Button variant="outline" size="sm" className="w-full justify-start gap-2 bg-transparent">
            <Calendar className="h-3 w-3" />
            Set Reminder
          </Button>
        </div>
      </div>
    </div>
  )
}
