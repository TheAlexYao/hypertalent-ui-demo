type ChatTab = "prompts" | "documents" | "insights" | "history"

const tabOptions: Array<{ id: ChatTab; label: string; description: string; icon: LucideIcon }> = [
  {
    id: "prompts",
    label: "Prompts",
    description: "Jump back into a conversation with one tap.",
    icon: MessageSquare,
  },
  {
    id: "documents",
    label: "Documents",
    description: "Review drafts and deliverables from recent sessions.",
    icon: FileText,
  },
  {
    id: "insights",
    label: "Insights",
    description: "Key takeaways and recommendations generated by AI.",
    icon: Lightbulb,
  },
  {
    id: "history",
    label: "History",
    description: "Search prior chats and continue the thread.",
    icon: History,
  },
]

export function ChatResultsPanel({ files }: ChatResultsPanelProps) {
  const [activeTab, setActiveTab] = useState<ChatTab>("prompts")
  const [searchQuery, setSearchQuery] = useState("")

  const filteredHistory = mockChatHistory.filter(
    (chat) =>
      chat.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
      chat.preview.toLowerCase().includes(searchQuery.toLowerCase()),
  )
  const historyCount = searchQuery.trim().length > 0 ? filteredHistory.length : mockChatHistory.length
  const tabCounts: Record<ChatTab, number> = {
    prompts: quickPrompts.length,
    documents: mockDocuments.length,
    insights: mockInsights.length,
    history: historyCount,
  }
  const activeTabMeta = tabOptions.find((tab) => tab.id === activeTab)

  const renderTabContent = () => {
    switch (activeTab) {
      case "prompts":
        return (
          <div className="space-y-2">
            {quickPrompts.map((prompt, index) => (
              <button
                key={index}
                type="button"
                className="w-full rounded-lg border border-border/40 bg-background/80 px-3 py-2 text-left text-sm text-foreground transition hover:border-border/60 hover:bg-background/90"
              >
                <div className="flex items-start gap-2">
                  <span className="mt-1 text-muted-foreground">
                    <MessageSquare className="h-4 w-4" />
                  </span>
                  <span className="leading-snug">{prompt}</span>
                </div>
              </button>
            ))}
          </div>
        )
      case "documents":
        return (
          <div className="space-y-2">
            {mockDocuments.map((doc) => (
              <div
                key={doc.id}
                className="rounded-lg border border-border/40 bg-background/80 px-3 py-2 text-sm text-foreground"
              >
                <div className="flex items-start justify-between gap-2">
                  <div className="flex flex-col gap-1">
                    <div className="flex items-center gap-2">
                      <FileText className="h-4 w-4 text-muted-foreground" />
                      <span className="font-medium leading-tight">{doc.title}</span>
                    </div>
                    <p className="text-xs text-muted-foreground">
                      {doc.type} • {doc.size}
                    </p>
                  </div>
                  <div className="flex items-center gap-1.5">
                    <Badge variant={doc.status === "Generated" ? "default" : "secondary"} className="text-[10px]">
                      {doc.status}
                    </Badge>
                    <Button
                      variant="ghost"
                      size="icon"
                      className="h-7 w-7 text-muted-foreground hover:text-foreground"
                      aria-label={`Download ${doc.title}`}
                    >
                      <Download className="h-3.5 w-3.5" />
                    </Button>
                  </div>
                </div>
              </div>
            ))}
          </div>
        )
      case "insights":
        return (
          <div className="space-y-2">
            {mockInsights.map((insight) => (
              <div
                key={insight.id}
                className="rounded-lg border border-border/40 bg-background/80 px-3 py-2 text-sm text-foreground"
              >
                <div className="flex items-start justify-between gap-2">
                  <h5 className="font-medium leading-tight">{insight.title}</h5>
                  <Badge variant="outline" className="text-[10px]">
                    {Math.round(insight.confidence * 100)}% confidence
                  </Badge>
                </div>
                <p className="mt-2 text-xs leading-relaxed text-muted-foreground">{insight.description}</p>
                <p className="mt-1 text-[11px] text-muted-foreground/80">{insight.sources} sources analyzed</p>
              </div>
            ))}
          </div>
        )
      case "history":
        return (
          <div className="space-y-3">
            <div className="relative">
              <Search className="absolute left-3 top-1/2 h-3 w-3 -translate-y-1/2 text-muted-foreground" />
              <Input
                placeholder="Search chat history..."
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                className="pl-9 text-sm"
              />
            </div>
            <div className="space-y-2">
              {filteredHistory.map((chat) => (
                <button
                  key={chat.id}
                  type="button"
                  className="w-full rounded-lg border border-border/40 bg-background/80 p-3 text-left transition hover:border-border/60 hover:bg-background/90"
                >
                  <div className="mb-1 flex items-center justify-between">
                    <div className="flex items-center gap-2">
                      <History className="h-3 w-3 text-muted-foreground" />
                      <span className="text-sm font-medium leading-tight text-foreground">{chat.title}</span>
                    </div>
                    <Badge variant="outline" className="text-[10px]">
                      {chat.messageCount} messages
                    </Badge>
                  </div>
                  <p className="text-xs text-muted-foreground">{chat.preview}</p>
                  <p className="mt-1 text-[11px] text-muted-foreground/70">
                    {new Date(chat.timestamp).toLocaleDateString()}
                  </p>
                </button>
              ))}
            </div>
          </div>
        )
    }
  }

  return (
    <div className="flex h-full flex-col gap-4">
      {files.length > 0 && (
        <div className="rounded-lg border border-border/40 bg-secondary/40 px-3 py-2">
          <p className="text-xs text-muted-foreground">
            Using context from {files.filter((f) => f.status === "completed").length} uploaded files
          </p>
        </div>
      )}

      <div className="space-y-3">
        <div className="space-y-1">
          <h4 className="text-sm font-semibold text-foreground">AI Assistant</h4>
          <p className="text-xs text-muted-foreground">Curate prompts, documents, and insights from ongoing collaborations.</p>
        </div>
        <div className="flex flex-col gap-2">
          {tabOptions.map((tab) => {
            const Icon = tab.icon
            const count = tabCounts[tab.id]
            return (
              <Button
                key={tab.id}
                type="button"
                size="sm"
                variant="outline"
                className={cn(
                  getToggleButtonClasses(activeTab === tab.id),
                  "w-full items-center justify-between rounded-lg px-3 py-2 text-xs font-medium",
                )}
                onClick={() => setActiveTab(tab.id)}
              >
                <span className="flex items-center gap-2">
                  <Icon className="h-3.5 w-3.5" />
                  {tab.label}
                </span>
                <Badge variant="secondary" className="text-[10px]">
                  {count}
                </Badge>
              </Button>
            )
          })}
        </div>
      </div>

      <div className="flex-1 overflow-y-auto pr-1">
        <div className="rounded-xl border border-border/40 bg-background/70 p-3 space-y-3">
          <div className="flex items-start justify-between gap-3">
            <div>
              <h5 className="text-sm font-semibold text-foreground">{activeTabMeta?.label}</h5>
              {activeTabMeta?.description && (
                <p className="text-xs text-muted-foreground">{activeTabMeta.description}</p>
              )}
            </div>
            <Badge variant="outline" className="text-[10px] uppercase tracking-wide">
              {tabCounts[activeTab]} {tabCounts[activeTab] === 1 ? "item" : "items"}
            </Badge>
          </div>
          {renderTabContent()}
        </div>
      </div>

      <div className="space-y-3 border-t border-border/30 pt-3">
        <div className="space-y-1">
          <h4 className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">Quick Actions</h4>
          <p className="text-xs text-muted-foreground">Generate new outputs without leaving the conversation.</p>
        </div>
        <div className="space-y-2">
          {assistantActions.map((action) => {
            const Icon = action.icon
            return (
              <Button
                key={action.id}
                variant="outline"
                size="sm"
                className="w-full justify-between gap-2 bg-transparent"
              >
                <span className="flex items-center gap-3 text-left">
                  <Icon className="h-3 w-3" />
                  <span className="flex flex-col items-start">
                    <span className="text-xs font-medium text-foreground">{action.label}</span>
                    <span className="text-[11px] text-muted-foreground">{action.helper}</span>
                  </span>
                </span>
                <ArrowUpRight className="h-3 w-3 text-muted-foreground" />
              </Button>
            )
          })}
        </div>
      </div>
    </div>
  )
}
